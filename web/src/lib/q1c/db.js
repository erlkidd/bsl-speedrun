const tables = new Map(); // ключ — ИМЯ В ВЕРХНЕМ РЕГИСТРЕ
export const norm = (s) => String(s).toUpperCase().replace(/Ё/g, "Е");

function def(name, kind, title, fields, extra = {}) {
  const t = { name, kind, title, fields: fields.map(([n, type, role = "attr"]) => ({ n, type, role })), rows: [], ...extra };
  t.col = new Map(t.fields.map((f) => [norm(f.n), f.n]));
  tables.set(norm(name), t);
  return t;
}
function add(t, row, name) {
  for (const f of t.fields) if (!(f.n in row)) row[f.n] = f.type === "Булево" ? false : f.type.startsWith("Число") ? 0 : f.type.startsWith("Строка") ? "" : null;
  Object.defineProperty(row, "__t", { value: t });
  if (name) Object.defineProperty(row, "__name", { value: name });
  if (t.kind !== "register" && t.kind !== "tabular") row.Ссылка = row;
  t.rows.push(row);
  return row;
}

