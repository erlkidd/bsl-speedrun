const fmtDate = (d, time = true) => {
  const p = (n) => String(n).padStart(2, "0");
  const base = `${p(d.getUTCDate())}.${p(d.getUTCMonth() + 1)}.${d.getUTCFullYear()}`;
  const t = d.getUTCHours() || d.getUTCMinutes() || d.getUTCSeconds();
  return time && t ? `${base} ${d.getUTCHours()}:${p(d.getUTCMinutes())}:${p(d.getUTCSeconds())}` : base;
};
export function presentation(v) {
  if (v === null) return "NULL";
  if (v === undefined) return "";
  if (v instanceof Date) return fmtDate(v);
  if (typeof v === "boolean") return v ? "Да" : "Нет";
  if (typeof v === "number") return Number.isInteger(v) ? String(v) : String(Math.round(v * 1e4) / 1e4);
  if (typeof v === "object" && v.__empty) return "";
  if (typeof v === "object" && v.__t) {
    const t = v.__t;
    if (t.kind === "enum") return v.__pres;
    if (t.kind === "document") return `${t.title} ${v.Номер} от ${fmtDate(v.Дата, false)}`;
    if (t.name.startsWith("ПланСчетов")) return v.Код;
    return v.Наименование ?? "";
  }
  return String(v);
}
